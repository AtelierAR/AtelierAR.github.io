// Fits the north (p67) and south (p68) volumes so every face area equals the deck value,
// then prints the parameters for src/geometry/volumeParams.js.
// Initial guesses come from the p51 / p53 section drawings (slopes measured at 2.3 px/ft).
import { NORTH, SOUTH } from '../src/data.js';
import { fitVolume, volumeMeasures } from '../src/geometry/volume.js';

const GUESS = {
  north: { a: 0.08, D: 100, b: 0.21, H: 112, c: -0.22, e: -0.12, tE: 0.05, tW: 0.05 },
  south: { a: 0.12, D: 80, b: 0.14, H: 112, c: -0.26, e: -0.12, tE: 0.05, tW: 0.05 },
};

for (const b of [NORTH, SOUTH]) {
  const p = fitVolume(b, GUESS[b.key]);
  const m = volumeMeasures(p);
  console.log(b.key, JSON.stringify(Object.fromEntries(Object.entries(p).map(([k, v]) => [k, +v.toFixed(9)]))));
  console.log('  areas', Object.fromEntries(Object.entries(m.areas).map(([k, v]) => [k, +v.toFixed(3)])));
  console.log('  faceHeight', m.faceHeight.toFixed(4), 'topWidth', m.faceTopWidth.toFixed(4), 'depth', m.depth.toFixed(3));
  console.log('  verts', Object.fromEntries(Object.entries(m.v).map(([k, v]) => [k, v.map((n) => +n.toFixed(1))])));
}

if (process.argv.includes('--write')) {
  const { writeFileSync } = await import('node:fs');
  const out = {};
  for (const b of [NORTH, SOUTH]) out[b.key] = fitVolume(b, GUESS[b.key]);
  writeFileSync(
    new URL('../src/geometry/volumeParams.js', import.meta.url),
    `// Generated by \`npm run fit -- --write\` (scripts/fit-volumes.mjs). Do not edit by hand.\n` +
      `// a, e: front tilt and underside slope measured on p51 / p53. Others solved so every\n` +
      `// face area equals p67 (north) / p68 (south).\n` +
      `export const VOLUME_PARAMS = ${JSON.stringify(out, null, 2)};\n`,
  );
  console.log('wrote src/geometry/volumeParams.js');
}
